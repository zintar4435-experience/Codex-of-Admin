"""
Расположение сервера — для режима «За границей» приложения Codex of Connect.

Зачем. Приложение по умолчанию пускает российские сайты и приложения МИМО
сервера (напрямую): оно рассчитано на людей в России, которым российские
сервисы нужны со своего адреса. Для человека за границей всё наоборот:
российские сервисы (банки, Госуслуги, маркетплейсы) не пускают иностранные
адреса, и ходить к ним нужно ЧЕРЕЗ сервер в России, а всё остальное —
напрямую.

Как это доезжает до приложения. Админ один раз ставит переключатель
«Сервер в России / Не в России» в настройках панели. Панель кладёт метку
`coc_region=ru|intl` в каждую ссылку, которую понимает приложение (VLESS,
NaiveProxy, SSH). Приложение, увидев метку, само включает нужный режим и не
даёт его сменить. Ссылки без метки (чужие панели) приложение считает
«чужим сервером» — там режим выбирает пользователь вручную.

Значения:
  intl — сервер НЕ в России (по умолчанию). Приложение работает как всегда.
  ru   — сервер в России. Приложение переворачивает правила: российское
         через сервер, остальное напрямую.

По умолчанию intl: уже работающие серверы после обновления панели ведут
себя ровно как раньше.
"""
from app.models import Setting

SETTING_KEY = "server_region"
REGIONS = ("intl", "ru")
DEFAULT = "intl"

# Имя параметра в ссылке. Нестандартное (с префиксом приложения), чтобы не
# пересечься с параметрами Xray/sing-box; чужие клиенты его просто игнорируют.
LINK_PARAM = "coc_region"


def current() -> str:
    """Текущее расположение сервера. Любое неизвестное значение — DEFAULT:
    битая запись в БД не должна переворачивать режим у всех клиентов."""
    value = (Setting.get(SETTING_KEY, DEFAULT) or DEFAULT).strip().lower()
    return value if value in REGIONS else DEFAULT
